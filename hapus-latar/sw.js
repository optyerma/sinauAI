// Service worker: simpan aplikasi, library MediaPipe, dan model agar bisa dipakai tanpa internet.
const CACHE = "hapus-latar-v1";
const FILES = ["./", "index.html", "manifest.webmanifest", "icons/icon-192.png", "icons/icon-512.png", "icons/apple-touch-icon.png"];
// Berkas dari CDN & model memakai URL berversi, jadi aman disajikan dari cache lebih dulu.
const IMMUTABLE = [/^https:\/\/cdn\.jsdelivr\.net\/npm\/@mediapipe\/tasks-vision@/, /^https:\/\/storage\.googleapis\.com\/mediapipe-models\//];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = req.url;

  if (IMMUTABLE.some((re) => re.test(url))) {
    e.respondWith(
      caches.match(req).then((hit) => hit || fetch(req).then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
        return res;
      }))
    );
    return;
  }

  // Berkas aplikasi: jaringan dulu, cadangan dari cache saat offline.
  if (new URL(url).origin !== location.origin) return;
  e.respondWith(
    fetch(req)
      .then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
        return res;
      })
      .catch(() => caches.match(req).then((r) => r || caches.match("index.html")))
  );
});
